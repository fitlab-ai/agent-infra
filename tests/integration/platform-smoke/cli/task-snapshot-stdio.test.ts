import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createTempDir, gitSafeEnv, initIsolatedGitRepo, INTERNAL_CLI_PATH, onPlatforms, taskWorkspaceProject, taskWorkspaceRoot } from '../../../helpers.ts';

test('snapshot runs Git without a stdin pipe and preserves the status output', onPlatforms('linux', 'darwin'), () => {
  const root = createTempDir('snapshot-stdio-');
  initIsolatedGitRepo(root);
  const id = 'TASK-20260101-000001';
  const dir = path.join(taskWorkspaceRoot(root), 'active', id);
  fs.mkdirSync(dir, { recursive: true });
  fs.mkdirSync(path.join(root, '.agents'), { recursive: true });
  fs.writeFileSync(path.join(root, '.agents', '.airc.json'), JSON.stringify({ project: taskWorkspaceProject(root) }));
  fs.writeFileSync(path.join(dir, 'task.md'), '# Task\n');
  fs.writeFileSync(path.join(root, 'untracked.txt'), 'content');
  const realGit = spawnSync('which', ['git'], { encoding: 'utf8' }).stdout.trim();
  const bin = path.join(root, 'test-bin');
  fs.mkdirSync(bin);
  fs.writeFileSync(path.join(bin, 'git'), `#!/bin/sh\nif [ ! -c /dev/stdin ]; then echo stdin-pipe >&2; exit 91; fi\nif [ "$TASK04_FAIL_STATUS" = yes ] && [ "$1" = -c ]; then echo git-status-probe >&2; exit 37; fi\nexec "${realGit}" "$@"\n`, { mode: 0o755 });
  const env = gitSafeEnv({ PATH: `${bin}${path.delimiter}${process.env.PATH}` });
  const result = spawnSync(process.execPath, [INTERNAL_CLI_PATH, 'task-snapshot', id, '--format', 'json'], { cwd: root, encoding: 'utf8', env });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  const snapshot = JSON.parse(result.stdout);
  const actual = spawnSync(realGit, ['-c', 'core.quotePath=true', 'status', '--short', '--untracked-files=all'], { cwd: root, encoding: 'utf8', env });
  assert.equal(actual.status, 0, actual.stderr);
  assert.equal(snapshot.observations.find((observation: { name: string }) => observation.name === 'git').output, actual.stdout.replace(/\r?\n$/, ''));
  const failed = spawnSync(process.execPath, [INTERNAL_CLI_PATH, 'task-snapshot', id, '--format', 'json'], { cwd: root, encoding: 'utf8', env: { ...env, TASK04_FAIL_STATUS: 'yes' } });
  assert.equal(failed.status, 1);
  const error = JSON.parse(failed.stdout).error;
  assert.equal(error.code, 'SNAPSHOT_GIT_FAILED');
  assert.match(error.message, /git-status-probe/);
});
